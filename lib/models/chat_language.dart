/// Detects the language style of a short chatbot message.
///
/// Returns null when there is too little language-specific evidence, allowing
/// callers to use a recent user message for short follow-ups such as "why?".
ChatLanguage? detectChatLanguage(String text) {
  final words = text
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9\s]'), ' ')
      .split(RegExp(r'\s+'))
      .where((word) => word.isNotEmpty)
      .toSet();

  final tagalogScore = words.intersection(_tagalogSignals).length;
  final englishScore = words.intersection(_englishSignals).length;
  final hasTagalog = tagalogScore >= 2;
  final hasEnglish = englishScore >= 2;

  if (hasTagalog && englishScore > 0) return ChatLanguage.taglish;
  if (hasTagalog) return ChatLanguage.tagalog;
  if (hasEnglish) return ChatLanguage.english;
  return null;
}
